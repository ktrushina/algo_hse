
def tracer(func):
    # Храним текущую глубину рекурсии в списке
    depth = [0]

    # Обёртка для отслеживания вызовов функции
    def wrapper(*args, **kwargs):
        # Создаём отступ в зависимости от глубины рекурсии
        indent = "  " * depth[0]

        # Выводим имя функции и её аргументы при входе
        print(f"{indent}→ {func.__name__}{args}")

        # Увеличиваем глубину перед вызовом функции
        depth[0] += 1

        try:
            # Вызываем исходную функцию
            result = func(*args, **kwargs)

            # Выводим результат после завершения вызова
            print(f"{indent}← {func.__name__} = {result}")

            return result
        finally:
            # Уменьшаем глубину при выходе из функции
            # Даже если во время выполнения возникла ошибка
            depth[0] -= 1

    return wrapper





